#!/usr/bin/env python3
"""Render the generated shiftability audit report."""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path


def load(path: Path) -> dict:
    return json.loads(path.read_text())


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--refs", default="work/shift/abs_refs.json")
    ap.add_argument("--blobs", default="work/shift/blob_scan.json")
    ap.add_argument("--symbols", default="work/shift/symbols.json")
    ap.add_argument("--out", default="docs/shiftability-audit.md")
    args = ap.parse_args()

    refs = load(Path(args.refs))
    blobs = load(Path(args.blobs))
    symbols = load(Path(args.symbols))
    summary = refs["summary"]
    rom = summary["rom"]

    lines: list[str] = []
    lines.append("# Shiftability audit")
    lines.append("")
    lines.append(
        "Generated by `make -f Makefile.shift audit`.  Do not edit by hand; "
        "change the audit scripts or the source and regenerate."
    )
    lines.append("")
    lines.append("## Baseline")
    lines.append("")
    lines.append(f"- Symbols parsed: **{symbols['summary']['symbols']}**")
    lines.append(f"- Sections parsed: **{symbols['summary']['sections']}**")
    lines.append(
        f"- Assembly address references: **{summary['records']}** "
        f"({summary['unique_values']} unique values)"
    )
    lines.append("")
    lines.append("## ROM references")
    lines.append("")
    lines.append(f"- ROM records: **{rom['records']}**")
    lines.append(f"- `.4byte`/`.word` literals: **{rom['literals']}**")
    lines.append(f"- `ldr =0x08...` reference comments: **{rom['status'].get('reference', 0)}**")
    lines.append(f"- Unique ROM values: **{rom['unique_values']}**")
    lines.append(f"- Status: `{rom['status']}`")
    lines.append("")
    lines.append("### Literal targets by section")
    lines.append("")
    lines.append("| Section | Literals |")
    lines.append("|---|---:|")
    for section, count in rom["literal_target_sections"].items():
        lines.append(f"| `{section}` | {count} |")
    lines.append("")
    lines.append("### ROM references by file")
    lines.append("")
    lines.append("| File | Refs |")
    lines.append("|---|---:|")
    for name, count in rom["by_file"].items():
        lines.append(f"| `{name}` | {count} |")
    lines.append("")
    lines.append("## Blob pointer candidates")
    lines.append("")
    lines.append(f"- Blobs: **{len(blobs['blobs'])}**")
    lines.append(f"- Classification: `{blobs['summary']}`")
    lines.append("")
    lines.append("| Blob | Bytes | Pointer-like | Density | Classification |")
    lines.append("|---|---:|---:|---:|---|")
    for blob in sorted(
        blobs["blobs"],
        key=lambda b: (b.get("density", 0), b.get("hits", 0)),
        reverse=True,
    ):
        if blob.get("classification") in {"pointer_table", "possible_pointer_table"}:
            lines.append(
                f"| `{blob['path']}` | {blob.get('bytes', 0)} | "
                f"{blob.get('hits', 0)} | {blob.get('density', 0):.3f} | "
                f"{blob.get('classification')} |"
            )
    lines.append("")
    lines.append("## Whitelist / fixed addresses")
    lines.append("")
    lines.append(
        "- ROM header `0x08000000` and ARM entry `0x080000C0` are hardware-fixed."
    )
    lines.append(
        "- EWRAM, IWRAM, MMIO, palette, VRAM and OAM addresses are intentionally fixed."
    )
    lines.append(
        "- The baseline linker script keeps the RAM layout; only ROM code/data move."
    )
    lines.append("")
    lines.append("## Next actions")
    lines.append("")
    lines.append(
        "1. **SHIFT-003** — map every open ROM literal to a symbol/label; "
        "classify the remainder as whitelist."
    )
    lines.append(
        "2. **SHIFT-004** — review the pointer-table candidates; convert true "
        "tables to C/asm labels, leave graphics/audio raw."
    )
    lines.append(
        "3. **SHIFT-005/006** — rewrite the six disasm blobs and the remaining "
        "asm, then regenerate this report."
    )
    lines.append(
        "4. **SHIFT-007/008** — relocatable linker, `check_relocs --strict`, "
        "and padding/reorder shift tests."
    )
    lines.append("")

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"report: {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
