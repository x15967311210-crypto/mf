#!/usr/bin/env python3
"""Generate the relocatable map-screen OAM frame-data blob.

BUG-006
-------
``sBlob_5657a8_575a60`` (``data/Blob_5657a8_575a60.bin``, 66232 bytes) holds
the pause/map-screen frame records.  501 of its little-endian 32-bit words
point *inside the blob itself*: they are OAM-data pointers used by
``MapScreenDrawSpecialOam``/``PauseScreenProcessOam``.  A raw ``INCBIN`` keeps
those words at their baseline ROM addresses, so a shifted (+0x1000) link reads
stale frame data and draws no objective UI.

The generator reads the extracted bytes and the baseline ``mf_us.map`` (plus
``mf_us.elf`` for the static symbol address), scans every aligned word, and
renders a ``const u32[]`` initialiser.  Every word whose value lies in
``[blob_base, blob_base + blob_size)`` becomes an address-of-this-object
expression using the *target* offset, not the offset of the pointer word.  A
word at ``+0x10A0`` whose value is ``0x08565DA8`` (``blob_base + 0x600``)
becomes:

    (u32)((const u8*)sBlob_5657a8_575a60 + 0x600)

The assembler emits ``.word sBlob_5657a8_575a60+0x600``, so the word follows
the blob on any link.  All other words are emitted verbatim, except that a raw
data word whose value happens to fall inside the ROM window is written as an
unsigned decimal constant.  Those words are OAM/graphics data, not addresses,
and ``check_relocs.py`` scans C for ``0x08xxxxxx`` literals; hexadecimal there
would be a false relocation finding.  The baseline bytes (and therefore the
normal-build SHA1) must not change.

The baseline symbol address is checked against the address encoded in the
blob filename (``Blob_5657a8_575a60`` -> ``0x085657A8``).  Run this tool only
against the baseline map/ELF; a shifted or reordered map fails the check
instead of silently scanning the wrong range.

Usage
-----
    python3 tools/shift/gen_map_oam_blob.py --check
    python3 tools/shift/gen_map_oam_blob.py --write
    python3 tools/shift/gen_map_oam_blob.py            # print to stdout

Output is deterministic: fixed word order, no timestamps, four words per line.
"""

from __future__ import annotations

import argparse
import re
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from map_symbols import SymbolMap  # noqa: E402

BLOB_FILE = "Blob_5657a8_575a60.bin"
BLOB_SYMBOL = "sBlob_5657a8_575a60"
BLOB_SIZE = 0x102B8
EXPECTED_POINTERS = 501
WORDS_PER_LINE = 4
ROM_START = 0x08000000
ROM_END = 0x0A000000

BEGIN_MARKER = (
    "/* BEGIN GENERATED by tools/shift/gen_map_oam_blob.py: {name} */"
)
END_MARKER = "/* END GENERATED: {name} */"
DECLARATION = (
    f"static const u8 {BLOB_SYMBOL}[] = "
    f'INCBIN_U8("data/{BLOB_FILE}");'
)

BLOB_NAME_RE = re.compile(r"^Blob_([0-9a-fA-F]{6})_([0-9a-fA-F]{6})\.bin$")


class GenError(Exception):
    """The blob cannot be rendered safely."""


def baseline_address() -> int:
    match = BLOB_NAME_RE.match(BLOB_FILE)
    if not match:
        raise GenError(f"{BLOB_FILE}: not a Blob_xxxxxx_yyyyyy name")
    return 0x08000000 | int(match.group(1), 16)


def blob_bytes(data_root: Path) -> bytes:
    path = data_root / BLOB_FILE
    if not path.exists():
        raise GenError(
            f"{path}: missing extracted blob; pass --data-root "
            "(the main tree's data/ in a fresh worktree)"
        )
    data = path.read_bytes()
    if len(data) != BLOB_SIZE:
        raise GenError(
            f"{path}: {len(data)} bytes, expected 0x{BLOB_SIZE:X}"
        )
    if len(data) % 4 != 0:
        raise GenError(f"{path}: size is not a multiple of 4")
    return data


def blob_base(sm: SymbolMap) -> int:
    expected = baseline_address()
    for symbol in sm.symbols:
        if symbol.name == BLOB_SYMBOL:
            if symbol.addr != expected:
                raise GenError(
                    f"{BLOB_SYMBOL}: map/ELF address 0x{symbol.addr:08X}, "
                    f"expected baseline 0x{expected:08X}; use the baseline "
                    "mf_us.map and mf_us.elf"
                )
            return symbol.addr
    raise GenError(
        f"{BLOB_SYMBOL}: not found in map/ELF; build the baseline first"
    )


def pointer_offsets(data: bytes, base: int) -> dict[int, int]:
    """Map the offset of each self-pointer word to the offset it points at."""
    offsets: dict[int, int] = {}
    for offset in range(0, len(data), 4):
        value = struct.unpack_from("<I", data, offset)[0]
        if base <= value < base + len(data):
            offsets[offset] = value - base
    if len(offsets) != EXPECTED_POINTERS:
        raise GenError(
            f"{BLOB_FILE}: found {len(offsets)} self pointers, expected "
            f"{EXPECTED_POINTERS}; wrong baseline map or blob?"
        )
    return offsets


def pointer_expression(target: int) -> str:
    if target == 0:
        return f"(u32)((const u8*){BLOB_SYMBOL})"
    return f"(u32)((const u8*){BLOB_SYMBOL} + 0x{target:X})"


def render(data: bytes, base: int) -> str:
    pointers = pointer_offsets(data, base)
    words = len(data) // 4
    lines = [
        BEGIN_MARKER.format(name=BLOB_SYMBOL),
        f"static const u32 {BLOB_SYMBOL}[{words}] = {{",
    ]
    for line_start in range(0, len(data), 4 * WORDS_PER_LINE):
        values: list[str] = []
        for offset in range(line_start, min(line_start + 4 * WORDS_PER_LINE, len(data)), 4):
            if offset in pointers:
                values.append(pointer_expression(pointers[offset]))
            else:
                value = struct.unpack_from("<I", data, offset)[0]
                if ROM_START <= value < ROM_END:
                    # Raw data, not an address: keep check_relocs.py from
                    # reporting a ROM literal that has no symbol.
                    values.append(f"{value}U")
                else:
                    values.append(f"0x{value:08X}")
        lines.append("    " + ", ".join(values) + ",")
    lines.append("};")
    lines.append(
        f"typedef char {BLOB_SYMBOL}_size_check"
        f"[sizeof({BLOB_SYMBOL}) == {BLOB_SIZE} ? 1 : -1];"
    )
    lines.append(END_MARKER.format(name=BLOB_SYMBOL))
    return "\n".join(lines)


def marker_region(text: str) -> tuple[int, int] | None:
    begin = BEGIN_MARKER.format(name=BLOB_SYMBOL)
    end = END_MARKER.format(name=BLOB_SYMBOL)
    first = text.find(begin)
    if first < 0:
        return None
    if text.find(begin, first + 1) >= 0:
        raise GenError(f"{BLOB_SYMBOL}: duplicate begin marker")
    last = text.find(end, first)
    if last < 0:
        raise GenError(f"{BLOB_SYMBOL}: begin marker without end marker")
    return first, last + len(end)


def check_source(source: Path, block: str) -> list[str]:
    text = source.read_text()
    region = marker_region(text)
    if region is None:
        return [
            f"{source}: missing generated block for {BLOB_SYMBOL} "
            "(run --write after reviewing the diff)"
        ]
    start, end = region
    errors: list[str] = []
    if text[start:end] != block:
        errors.append(f"{source}: generated block for {BLOB_SYMBOL} is out of date")
    if DECLARATION in text:
        errors.append(f"{source}: {BLOB_SYMBOL} is still declared with INCBIN_U8")
    return errors


def write_source(source: Path, block: str) -> bool:
    text = source.read_text()
    region = marker_region(text)
    if region is not None:
        start, end = region
        if text[start:end] == block:
            return False
        source.write_text(text[:start] + block + text[end:])
        return True
    if text.count(DECLARATION) != 1:
        raise GenError(
            f"{source}: cannot find exactly one declaration {DECLARATION!r}"
        )
    source.write_text(text.replace(DECLARATION, block, 1))
    return True


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--map", default="mf_us.map", help="baseline linker map")
    ap.add_argument("--elf", default="mf_us.elf", help="baseline ELF")
    ap.add_argument("--data-root", default="data", help="extracted blob directory")
    ap.add_argument(
        "--source",
        default="src/data/menus/pause_screen_map_data.c",
        help="C source that owns the declaration",
    )
    ap.add_argument(
        "--check",
        action="store_true",
        help="fail if the generated block is out of date",
    )
    ap.add_argument(
        "--write",
        action="store_true",
        help="replace the INCBIN declaration with the generated block",
    )
    args = ap.parse_args()

    if args.check and args.write:
        print(
            "gen_map_oam_blob: --check and --write are mutually exclusive",
            file=sys.stderr,
        )
        return 2

    try:
        data = blob_bytes(Path(args.data_root))
        sm = SymbolMap.load(Path(args.map), Path(args.elf))
        base = blob_base(sm)
        block = render(data, base)
        if args.check:
            errors = check_source(Path(args.source), block)
        else:
            errors = []
    except (OSError, GenError) as exc:
        print(f"gen_map_oam_blob: {exc}", file=sys.stderr)
        return 1

    if args.check:
        if errors:
            for message in errors:
                print(f"gen_map_oam_blob: ERROR: {message}", file=sys.stderr)
            print("FAIL: generated map OAM blob is not up to date", file=sys.stderr)
            return 1
        print(
            f"PASS: {BLOB_SYMBOL} matches the baseline bytes with "
            f"{EXPECTED_POINTERS} self-relocating words"
        )
        return 0

    if not args.write:
        print(block)
        return 0

    try:
        changed = write_source(Path(args.source), block)
    except (OSError, GenError) as exc:
        print(f"gen_map_oam_blob: {exc}", file=sys.stderr)
        return 1
    print(
        f"gen_map_oam_blob: {args.source}: "
        f"{'updated' if changed else 'unchanged'}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
