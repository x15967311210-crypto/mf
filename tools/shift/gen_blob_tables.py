#!/usr/bin/env python3
"""Generate relocatable C arrays for the confirmed pointer-table data blobs.

SHIFT-004 classified seven extracted blobs as flat pointer tables
(``docs/blob-classification.md``).  Each blob is currently declared as

    static u8 sBlob_x_y[] = INCBIN_U8("data/Blob_x_y.bin");

so its pointer words stay raw absolute ROM addresses and break when the link
moves.  This tool reads each blob, resolves every aligned 32-bit word to a
symbol expression, and renders an equivalent ``u32[]`` initialiser with the
exact same byte size:

    static u32 sBlob_x_y[13] = {
        (u32)Dma2IntrCode + 1,
        ...
    };
    typedef char sBlob_x_y_size_check[
        sizeof(sBlob_x_y) == 52 ? 1 : -1];

The generated initialisers are byte-identical to the extracted blobs in the
baseline link.  ``--check`` verifies the checked-in C arrays still match the
baseline bytes; ``--write`` updates the three source files between the
generated markers.

Resolution rules
----------------
* The target symbol comes from ``mf_us.map`` merged with local ELF symbols
  (``map_symbols.SymbolMap``), exactly like ``audit_asm.py``.
* A global/weak target is referenced directly.  A static (``STB_LOCAL``)
  data target is not link-visible from another object, so the same
  global-anchor rule as ``apply_refs.py`` applies: emit a global symbol in the
  same output section plus the byte delta, e.g.
  ``sMinimapTilesGfx+0x1094``.
* ``Blob_a5224_a5258`` holds Thumb callback pointers.  The low bit is kept
  only when the underlying ELF symbol is ``STT_FUNC`` and the stored value has
  bit 0 set; no unconditional ``| 1``.

Usage
-----
    python3 tools/shift/gen_blob_tables.py --check
    python3 tools/shift/gen_blob_tables.py --write
    python3 tools/shift/gen_blob_tables.py            # print to stdout

The tool is deterministic: it uses the fixed blob table below, sorted ELF
symbols, and no timestamps.  It needs ``mf_us.map`` and ``mf_us.elf`` (the
baseline build) plus the extracted bytes under ``data/``.
"""

from __future__ import annotations

import argparse
import json
import re
import struct
import sys
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from map_symbols import SymbolMap  # noqa: E402

SYMBOL_RE = re.compile(r"^[A-Za-z_.$][\w.$@]*$")
BEGIN_MARKER = "/* BEGIN GENERATED by tools/shift/gen_blob_tables.py: {name} */"
END_MARKER = "/* END GENERATED: {name} */"

BINDING_LOCAL = 0
BINDING_GLOBAL = 1
BINDING_WEAK = 2
STT_FUNC = 2
SYMBOL_TYPES = {0, 1}  # NOTYPE, OBJECT; functions are not data anchors.
ANCHOR_SECTIONS = {".rodata", ".data"}


class GenError(Exception):
    """A blob cannot be rendered safely."""


@dataclass(frozen=True)
class BlobSpec:
    symbol: str
    file: str  # extracted bytes, relative to --data-root
    source: str  # C source that owns the declaration
    data_bytes: int  # database.json count
    const: bool


