def field_size(field: MixedField) -> int:
    return field.count if field.kind == "u8" else field.count * 4


def field_ctype(field: MixedField) -> str:
    return "u8" if field.kind == "u8" else "u32"


@dataclass(frozen=True)
class ElfSymbol:
    name: str
    value: int
    binding: int
    section: str


class ElfSymbols:
    """Minimal final-ELF reader: bindings, types, and data anchors."""

    def __init__(
        self,
        bindings: dict[tuple[str, int], int],
        all_bindings: dict[tuple[str, int], int],
        types: dict[tuple[str, int], int],
        globals_by_section: dict[str, list[ElfSymbol]],
    ):
        self._bindings = bindings
        self._all_bindings = all_bindings
        self._types = types
        self._globals_by_section = globals_by_section

    @classmethod
    def load(cls, path: Path) -> "ElfSymbols":
        data = path.read_bytes()
        if len(data) < 0x34 or data[:4] != b"\x7fELF" or data[4] != 1 or data[5] != 1:
            raise GenError(f"{path}: not a little-endian ELF32 file")

        e_shoff = struct.unpack_from("<I", data, 0x20)[0]
        e_shentsize = struct.unpack_from("<H", data, 0x2E)[0]
        e_shnum = struct.unpack_from("<H", data, 0x30)[0]
        e_shstrndx = struct.unpack_from("<H", data, 0x32)[0]
        if not e_shoff or not e_shnum or e_shentsize < 40:
            raise GenError(f"{path}: missing section headers")

        sections: list[tuple[int, int, int, int, int, int, int, int, int, int]] = []
        for i in range(e_shnum):
            off = e_shoff + i * e_shentsize
            if off + 40 > len(data):
                raise GenError(f"{path}: truncated section table")
            sections.append(struct.unpack_from("<IIIIIIIIII", data, off))

        if e_shstrndx >= len(sections):
            raise GenError(f"{path}: bad section-name table index")

        def cstring(offset: int) -> str:
            if offset < 0 or offset >= len(data):
                return ""
            end = data.find(b"\x00", offset)
            if end < 0:
                return ""
            return data[offset:end].decode("ascii", "replace")

        shstr = sections[e_shstrndx]
        section_names = {
            i: cstring(shstr[4] + sec[0]) for i, sec in enumerate(sections)
        }

        symtab = None
        for i, sec in enumerate(sections):
            if sec[1] == 2 and sec[9]:  # SHT_SYMTAB
                symtab = (i, sec)
                break
        if symtab is None:
            raise GenError(f"{path}: no symbol table")

        _, sec = symtab
        sym_off, sym_size, strtab_idx, entsize = sec[4], sec[5], sec[6], sec[9]
        if strtab_idx >= len(sections) or not entsize:
            raise GenError(f"{path}: bad symbol table")
        strtab = sections[strtab_idx]

        bindings: dict[tuple[str, int], int] = {}
        all_bindings: dict[tuple[str, int], int] = {}
        types: dict[tuple[str, int], int] = {}
        globals_by_section: dict[str, list[ElfSymbol]] = {}
        for off in range(sym_off, min(sym_off + sym_size, len(data)), entsize):
            if off + 16 > len(data):
                break
            st_name, st_value, _st_size, st_info, _st_other, st_shndx = (
                struct.unpack_from("<IIIBBH", data, off)
            )
            name = cstring(strtab[4] + st_name)
            if not name:
                continue
            binding = st_info >> 4
            sym_type = st_info & 0xF
            section = section_names.get(st_shndx, "")
            all_bindings[(name, st_value)] = binding
            types[(name, st_value)] = sym_type
            if section not in ANCHOR_SECTIONS:
                continue
            bindings[(name, st_value)] = binding
            if (
                binding in (BINDING_GLOBAL, BINDING_WEAK)
                and sym_type in SYMBOL_TYPES
                and SYMBOL_RE.match(name)
            ):
                globals_by_section.setdefault(section, []).append(
                    ElfSymbol(name, st_value, binding, section)
                )

        for symbols in globals_by_section.values():
            symbols.sort(key=lambda s: (s.value, s.name))

        return cls(bindings, all_bindings, types, globals_by_section)

    def binding(self, name: str, value: int) -> int | None:
        return self._bindings.get((name, value))

    def any_binding(self, name: str, value: int) -> int | None:
        return self._all_bindings.get((name, value))

    def symbol_type(self, name: str, value: int) -> int | None:
        return self._types.get((name, value))

    def anchor(self, addr: int, section: str) -> ElfSymbol | None:
        """Return the nearest global data anchor in *section* for *addr*."""
        candidates = self._globals_by_section.get(section)
        if not candidates:
            return None
        preceding = [s for s in candidates if s.value <= addr]
        if preceding:
            return max(preceding, key=lambda s: (s.value, s.name))
        return min(candidates, key=lambda s: (s.value, s.name))


def format_expression(symbol: str, offset: int) -> str:
    if offset == 0:
        return symbol
    if offset > 0:
        return f"{symbol}+0x{offset:X}"
    return f"{symbol}-0x{-offset:X}"


def target_parts(sm: SymbolMap, addr: int) -> tuple[dict, str, int, int]:
    """Resolve *addr* and return (target, symbol, symbol address, offset)."""
    target = sm.resolve(addr)
    if not target.get("known"):
        raise GenError(f"0x{addr:08X}: address is not mapped to a ROM section")
    symbol = target.get("symbol")
    if not symbol or not SYMBOL_RE.match(symbol):
        raise GenError(f"0x{addr:08X}: no usable symbol")
    offset = target.get("offset") or 0
    return target, symbol, addr - offset, offset


def resolve_expression(sm: SymbolMap, elf: ElfSymbols, addr: int) -> str:
    """symbol+offset, or a same-section global anchor for a local symbol."""
    target, symbol, symbol_addr, offset = target_parts(sm, addr)
    binding = elf.binding(symbol, symbol_addr)
    if binding == BINDING_LOCAL:
        section = target.get("section") or ""
        anchor = elf.anchor(addr, section)
        if anchor is None:
            raise GenError(
                f"0x{addr:08X}: local symbol {symbol} has no global "
                f"anchor in {section or '?'}"
            )
        return format_expression(anchor.name, addr - anchor.value)
    return format_expression(symbol, offset)


def pointer_expression(
    sm: SymbolMap, elf: ElfSymbols, value: int, thumb_blob: bool
) -> str:
    if thumb_blob:
        if not value & 1:
            raise GenError(
                f"0x{value:08X}: expected a Thumb function pointer (bit 0 set)"
            )
        # Resolve the raw stored value.  The ELF function symbol may already
        # carry the Thumb bit in st_value (this baseline does); resolving the
        # raw value keeps it either inside the symbol value or as a +1 offset
        # for an even-valued symbol.  Never add the bit unconditionally.
        _, symbol, symbol_addr, _offset = target_parts(sm, value)
        sym_type = elf.symbol_type(symbol, symbol_addr)
        if sym_type != STT_FUNC:
            raise GenError(
                f"0x{value:08X}: {symbol} is not an ELF STT_FUNC "
                f"(type {sym_type})"
            )
        binding = elf.any_binding(symbol, symbol_addr)
        if binding not in (BINDING_GLOBAL, BINDING_WEAK):
            raise GenError(
                f"0x{value:08X}: function symbol {symbol} is not "
                "link-visible (binding {binding})"
            )
        return f"(u32){resolve_expression(sm, elf, value)}"

    if value & 1:
        raise GenError(
            f"0x{value:08X}: unexpected low bit in a data pointer table"
        )
    return f"(u32){resolve_expression(sm, elf, value)}"


def struct_layout(fields: tuple[StructField, ...]) -> tuple[list[tuple[StructField, int, int]], int]:
    """Return (field, byte offset, byte size) plus the C struct size."""
    if not fields:
        raise GenError("struct blob has no fields")
    offset = 0
    alignment = 1
    layout: list[tuple[StructField, int, int]] = []
    for field in fields:
        try:
            size, field_alignment = FIELD_INFO[field.c_type]
        except KeyError:
            raise GenError(
                f"unsupported struct field type {field.c_type!r}"
            ) from None
        offset = (offset + field_alignment - 1) & ~(field_alignment - 1)
        layout.append((field, offset, size))
        offset += size
        alignment = max(alignment, field_alignment)
    size = (offset + alignment - 1) & ~(alignment - 1)
    return layout, size


def blob_bytes(spec: BlobSpec | MixedBlobSpec, data_root: Path) -> bytes:
    path = data_root / spec.file
    if not path.exists():
        raise GenError(
            f"{path}: missing extracted blob; pass --data-root (SHIFT-004 uses "
            "/home/x1596/proj/mf/data in a fresh worktree)"
        )
    data = path.read_bytes()
    if len(data) != spec.data_bytes:
        raise GenError(
            f"{path}: {len(data)} bytes, expected 0x{spec.data_bytes:X} "
            "from database.json"
        )
    if isinstance(spec, BlobSpec) and spec.fields:
        _, record_size = struct_layout(spec.fields)
        if record_size == 0 or len(data) % record_size != 0:
            raise GenError(
                f"{path}: size is not a multiple of the "
                f"{record_size}-byte struct"
            )
    elif len(data) % 4 != 0:
        raise GenError(f"{path}: size is not a multiple of 4")
    return data


def render_flat_block(
    spec: BlobSpec, data: bytes, sm: SymbolMap, elf: ElfSymbols
) -> str:
    count = len(data) // 4
    qualifier = "const " if spec.const else ""
    lines = [
        BEGIN_MARKER.format(name=spec.symbol),
        f"static {qualifier}u32 {spec.symbol}[{count}] = {{",
    ]
    thumb_blob = spec.symbol in THUMB_BLOBS
    for off in range(0, len(data), 4):
        value = struct.unpack_from("<I", data, off)[0]
        expr = pointer_expression(sm, elf, value, thumb_blob)
        lines.append(f"    {expr},")
    lines.append("};")
    lines.append(
        f"typedef char {spec.symbol}_size_check"
        f"[sizeof({spec.symbol}) == {len(data)} ? 1 : -1];"
    )
    lines.append(END_MARKER.format(name=spec.symbol))
    return "\n".join(lines)


def render_struct_block(
    spec: BlobSpec, data: bytes, sm: SymbolMap, elf: ElfSymbols
) -> str:
    if not spec.struct_name:
        raise GenError(f"{spec.symbol}: struct spec has no struct name")
    layout, record_size = struct_layout(spec.fields)
    count = len(data) // record_size
    qualifier = "const " if spec.const else ""
    lines = [
        BEGIN_MARKER.format(name=spec.symbol),
        f"struct {spec.struct_name} {{",
    ]
    for field in spec.fields:
        lines.append(f"    {field.c_type} {field.name};")
    lines.append("};")
    lines.append("")
    lines.append(
        f"static {qualifier}struct {spec.struct_name} {spec.symbol}[{count}] = {{"
    )
    for index in range(count):
        base = index * record_size
        values: list[str] = []
        for field, offset, size in layout:
            raw = int.from_bytes(data[base + offset : base + offset + size], "little")
            if field.c_type.endswith("*"):
                if raw & 1:
                    raise GenError(
                        f"{spec.file}: entry {index} field {field.name} "
                        f"0x{raw:08X} has the low bit set"
                    )
                values.append(f"({field.c_type})((u32){resolve_expression(sm, elf, raw)})")
            else:
                values.append(f"0x{raw:X}")
        lines.append("    { " + ", ".join(values) + " },")
    lines.append("};")
    lines.append(
        f"typedef char struct_{spec.struct_name}_size_check"
        f"[sizeof(struct {spec.struct_name}) == {record_size} ? 1 : -1];"
    )
    lines.append(
        f"typedef char {spec.symbol}_size_check"
        f"[sizeof({spec.symbol}) == {len(data)} ? 1 : -1];"
    )
    lines.append(END_MARKER.format(name=spec.symbol))
    return "\n".join(lines)


def render_block(spec: BlobSpec, data: bytes, sm: SymbolMap, elf: ElfSymbols) -> str:
    if spec.fields:
        return render_struct_block(spec, data, sm, elf)
    return render_flat_block(spec, data, sm, elf)


def render_mixed_block(
    spec: MixedBlobSpec, data: bytes, sm: SymbolMap, elf: ElfSymbols
) -> str:
    expected = sum(field_size(field) for field in spec.fields)
    if expected != len(data):
        raise GenError(
            f"{spec.file}: field model covers {expected} bytes, blob has "
            f"{len(data)}"
        )

    qualifier = "const " if spec.const else ""
    lines = [
        BEGIN_MARKER.format(name=spec.symbol),
        "static struct {",
    ]
    for field in spec.fields:
        lines.append(f"    {field_ctype(field)} {field.name}[{field.count}];")
    lines.append(f"}} {spec.symbol} = {{")

    offset = 0
    for field in spec.fields:
        lines.append(f"    /* +0x{offset:03X} {field.name} */")
        lines.append("    {")
        size = field_size(field)
        if field.kind == "u8":
            for start in range(0, size, 12):
                values = data[offset + start : offset + min(start + 12, size)]
                rendered = ", ".join(f"0x{value:02X}" for value in values)
                lines.append(f"        {rendered},")
        else:
            thumb = field.kind == "thumb"
            for pos in range(offset, offset + size, 4):
                value = struct.unpack_from("<I", data, pos)[0]
                expr = pointer_expression(sm, elf, value, thumb)
                lines.append(f"        {expr},")
        lines.append("    },")
        offset += size

    lines.append("};")
    lines.append(
        f"typedef char {spec.symbol}_size_check"
        f"[sizeof({spec.symbol}) == {len(data)} ? 1 : -1];"
    )
    lines.append(END_MARKER.format(name=spec.symbol))
    return "\n".join(lines)


def marker_region(text: str, symbol: str) -> tuple[int, int] | None:
    begin = BEGIN_MARKER.format(name=symbol)
    end = END_MARKER.format(name=symbol)
    first = text.find(begin)
    if first < 0:
        return None
    if text.find(begin, first + 1) >= 0:
        raise GenError(f"{symbol}: duplicate begin marker")
    last = text.find(end, first)
    if last < 0:
        raise GenError(f"{symbol}: begin marker without end marker")
    return first, last + len(end)


def check_source(
    spec: BlobSpec | MixedBlobSpec, path: Path, block: str
) -> list[str]:
    errors: list[str] = []
    text = path.read_text()
    region = marker_region(text, spec.symbol)
    if region is None:
        errors.append(
            f"{path}: missing generated block for {spec.symbol} "
            "(run --write after reviewing the diff)"
        )
        return errors
    start, end = region
    if text[start:end] != block:
        errors.append(
            f"{path}: generated block for {spec.symbol} is out of date"
        )
    if f"{spec.symbol}[] = INCBIN_U8" in text:
        errors.append(f"{path}: {spec.symbol} is still declared with INCBIN_U8")
    return errors


def write_source(
    spec: BlobSpec | MixedBlobSpec, path: Path, block: str
) -> bool:
    text = path.read_text()
    region = marker_region(text, spec.symbol)
    if region is not None:
        start, end = region
        if text[start:end] == block:
            return False
        path.write_text(text[:start] + block + text[end:])
        return True

    declaration = (
        f"static {'const ' if spec.const else ''}u8 {spec.symbol}[] = "
        f'INCBIN_U8("data/{spec.file}");'
    )
    if text.count(declaration) != 1:
        raise GenError(
            f"{path}: cannot find exactly one declaration {declaration!r}"
        )
    path.write_text(text.replace(declaration, block, 1))
    return True


def load_database_sizes(path: Path) -> dict[str, int]:
    if not path.exists():
        raise GenError(f"{path}: missing database.json")
    sizes: dict[str, int] = {}
    for entry in json.loads(path.read_text()):
        blob_path = entry.get("path", "")
        if not blob_path.startswith("Blob"):
            continue
        count = entry.get("count")
        if count is not None:
            sizes[blob_path] = int(count, 16) if isinstance(count, str) else int(count)
    return sizes


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--map", default="mf_us.map", help="baseline linker map")
    ap.add_argument("--elf", default="mf_us.elf", help="baseline ELF")
    ap.add_argument("--data-root", default="data", help="extracted blob directory")
    ap.add_argument("--database", default="database.json", help="blob metadata")
    ap.add_argument(
        "--check",
        action="store_true",
        help="fail if a generated block or blob size is out of date",
    )
    ap.add_argument(
        "--write",
        action="store_true",
        help="replace the INCBIN declarations with generated blocks",
    )
    args = ap.parse_args()

    if args.check and args.write:
        print("gen_blob_tables: --check and --write are mutually exclusive", file=sys.stderr)
        return 2

    try:
        sizes = load_database_sizes(Path(args.database))
        sm = SymbolMap.load(Path(args.map), Path(args.elf))
        elf = ElfSymbols.load(Path(args.elf))
    except (OSError, GenError, json.JSONDecodeError) as exc:
        print(f"gen_blob_tables: {exc}", file=sys.stderr)
        return 1

    errors: list[str] = []
    changed = 0
    by_source: dict[Path, list[tuple[BlobSpec | MixedBlobSpec, str]]] = {}
    for spec in (*BLOBS, *MIXED_BLOBS):
        database_size = sizes.get(spec.file)
        if database_size is not None and database_size != spec.data_bytes:
            errors.append(
                f"{spec.file}: database count 0x{database_size:X} does not "
                f"match tool table 0x{spec.data_bytes:X}"
            )
            continue
        try:
            data = blob_bytes(spec, Path(args.data_root))
            if isinstance(spec, MixedBlobSpec):
                block = render_mixed_block(spec, data, sm, elf)
            else:
                block = render_block(spec, data, sm, elf)
        except GenError as exc:
            errors.append(str(exc))
            continue
        by_source.setdefault(Path(spec.source), []).append((spec, block))

    if args.check:
        for source, entries in sorted(by_source.items(), key=lambda item: str(item[0])):
            for spec, block in entries:
                errors.extend(check_source(spec, source, block))
        if errors:
            for message in errors:
                print(f"gen_blob_tables: ERROR: {message}", file=sys.stderr)
            print("FAIL: generated blob arrays are not up to date", file=sys.stderr)
            return 1
        struct_count = sum(1 for spec in BLOBS if spec.fields)
        flat_count = len(BLOBS) - struct_count
        print(
            f"PASS: {flat_count} pointer-table blobs + {len(MIXED_BLOBS)} "
            f"mixed + {struct_count} struct match the baseline bytes and "
            f"checked-in C arrays"
        )
        return 0

    if not args.write:
        for source, entries in sorted(by_source.items(), key=lambda item: str(item[0])):
            for spec, block in entries:
                print(f"/* {source}: {spec.symbol} */")
                print(block)
                print()
        if errors:
            for message in errors:
                print(f"gen_blob_tables: ERROR: {message}", file=sys.stderr)
            return 1
        return 0

    try:
        for source, entries in sorted(by_source.items(), key=lambda item: str(item[0])):
            for spec, block in entries:
                if write_source(spec, source, block):
                    changed += 1
                    print(f"updated {source}: {spec.symbol}")
    except (OSError, GenError) as exc:
        print(f"gen_blob_tables: {exc}", file=sys.stderr)
        return 1

    if errors:
        for message in errors:
            print(f"gen_blob_tables: ERROR: {message}", file=sys.stderr)
        print("FAIL: not every blob was converted", file=sys.stderr)
        return 1
    print(f"gen_blob_tables: {changed} block(s) updated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
