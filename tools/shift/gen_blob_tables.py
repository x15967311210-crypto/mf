#!/usr/bin/env python3
"""Generate relocatable C arrays for the classified data blobs.

SHIFT-004 classified seven extracted blobs as flat pointer tables and three as
``possible`` (``docs/blob-classification.md``).  Each blob is currently
declared as

    static u8 sBlob_x_y[] = INCBIN_U8("data/Blob_x_y.bin");

so its pointer words stay raw absolute ROM addresses and break when the link
moves.  This tool reads each blob, resolves every pointer to a symbol
expression, and renders either an equivalent ``u32[]`` initialiser, a struct
array, or a mixed field model with the exact same byte size:

    static u32 sBlob_x_y[13] = {
        (u32)Dma2IntrCode + 1,
        ...
    };
    typedef char sBlob_x_y_size_check[
        sizeof(sBlob_x_y) == 52 ? 1 : -1];

The generated initialisers are byte-identical to the extracted blobs in the
baseline link.  ``--check`` verifies the checked-in C arrays still match the
baseline bytes; ``--write`` updates the source files between the generated
markers.

Mixed blobs (SHIFT-006b) are not flat pointer arrays.  ``Blob_79c170_79c27c``
is modelled as one C struct whose fields cover the whole blob; only the Thumb
code pointers and the 21-entry text-pointer array become symbol expressions,
every other byte is emitted verbatim.  The positional struct initialiser keeps
the exact byte offsets and a compile-time size check catches padding.

``Blob_74dc48_74e620`` (SHIFT-006b2) is a 210-entry array of 12-byte records
(``u8`` flags, three unknown bytes, two ``u16`` coordinates, one pointer), so
it is rendered as a struct array instead of a flat word array:

    struct EndingImageLine {
        u8 flags;
        ...
        const u8* pText;
    };
    static const struct EndingImageLine sBlob_74dc48_74e620[210] = {
        { 0x2, 0x0, 0x0, 0x0, 0x78, 0x28, (const u8*)((u32)sResultsTextPal+0xBA) },
        ...
    };

Resolution rules
----------------
* The target symbol comes from ``mf_us.map`` merged with local ELF symbols
  (``map_symbols.SymbolMap``), exactly like ``audit_asm.py``.
* A global/weak target is referenced directly.  A static (``STB_LOCAL``)
  data target is not link-visible from another object, so the same
  global-anchor rule as ``apply_refs.py`` applies: emit a global symbol in the
  same output section plus the byte delta, e.g.
  ``sMinimapTilesGfx+0x1094``.
* ``Blob_a5224_a5258`` holds Thumb callback pointers.  The low bit is kept
  only when the underlying ELF symbol is ``STT_FUNC`` and the stored value has
  bit 0 set; no unconditional ``| 1``.

Usage
-----
    python3 tools/shift/gen_blob_tables.py --check
    python3 tools/shift/gen_blob_tables.py --write
    python3 tools/shift/gen_blob_tables.py            # print to stdout

The tool is deterministic: it uses the fixed blob table below, sorted ELF
symbols, and no timestamps.  It needs ``mf_us.map`` and ``mf_us.elf`` (the
baseline build) plus the extracted bytes under ``data/``.
"""

